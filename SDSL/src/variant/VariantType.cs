namespace SDSL;

/// <summary>
/// Specifies the <see cref="Variant"/> type catagories.
/// </summary>
public enum VariantType
{
	/// <summary>
	/// The Nil type.
	/// </summary>
	Nil,
	
	/// <summary>
	/// The Bool type.
	/// </summary>
	Bool,
	
	/// <summary>
	/// The Number type.
	/// </summary>
	Number,
	
	/// <summary>
	/// The DateTime type.
	/// </summary>
	DateTime,
	
	/// <summary>
	/// The TimeSpan type.
	/// </summary>
	TimeSpan,
	
	/// <summary>
	/// The String type.
	/// </summary>
	String,
	
	/// <summary>
	/// The Object type.
	/// </summary>
	Object,
}